#include "data.h"
#include "../includes/include.h"

struct dpi_payload {
    int level;
    unsigned char buf[17];
};

static const struct dpi_payload payload_table[] = {
    {50,    {0x08, 0x07, 0x00, 0x00, 0x10, 0x04, 0x00, 0x00, 0x00, 0x55, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xdd}},
    {800,   {0x08, 0x07, 0x00, 0x00, 0x10, 0x04, 0x0f, 0x0f, 0x00, 0x37, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xdd}},
    {6400,  {0x08, 0x07, 0x00, 0x00, 0x10, 0x04, 0x7f, 0x7f, 0x00, 0x57, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xdd}},
    {12750, {0x08, 0x07, 0x00, 0x00, 0x10, 0x04, 0xfe, 0xfe, 0x00, 0x59, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xdd}},
    {12800, {0x08, 0x07, 0x00, 0x00, 0x10, 0x04, 0xff, 0xff, 0x00, 0x57, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xdd}},
    {19200, {0x08, 0x07, 0x00, 0x00, 0x10, 0x04, 0x7f, 0x7f, 0x44, 0x13, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xdd}},
    {26000, {0x08, 0x07, 0x00, 0x00, 0x10, 0x04, 0x07, 0x07, 0x88, 0xbf, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xdd}}
};

void get_payload(int level, unsigned char *buf) {
    if (level < 50) level = 50;
    if (level > 26000) level = 26000;
    level = (level / 50) * 50;

    for (unsigned long i = 0; i < sizeof(payload_table) / sizeof(payload_table[0]); i++) {
        if (payload_table[i].level == level) {
            for (int j = 0; j < 17; j++) {
                buf[j] = payload_table[i].buf[j];
            }
            return;
        }
    }

    int N = (level / 50) - 1;
    int r = N % 256;
    int q = N / 256;

    unsigned char band = (unsigned char)(q * 0x44);
    unsigned char low_byte = (unsigned char)r;
    unsigned char checksum = (unsigned char)((0x55 - 2 * r - band) & 0xFF);

    buf[0] = 0x08;
    buf[1] = 0x07;
    buf[2] = 0x00;
    buf[3] = 0x00;
    buf[4] = 0x10;
    buf[5] = 0x04;
    buf[6] = low_byte;
    buf[7] = low_byte;
    buf[8] = band;
    buf[9] = checksum;
    buf[10] = 0x00;
    buf[11] = 0x00;
    buf[12] = 0x00;
    buf[13] = 0x00;
    buf[14] = 0x00;
    buf[15] = 0x00;
    buf[16] = 0xdd;
}
